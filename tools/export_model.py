"""Quantize the trained model and generate C weights + parity test vectors.

Outputs:
  components/model_data/model_weights.h
  tests/generated/tinyai_golden.h
  tests/generated/tinyai_golden.c
  model/model_manifest.json

The exported int8 weights are the ones evaluated by tools/evaluate.py. No
accuracy number is invented here; the manifest embeds the measured quantized
evaluation.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from model_pipeline import (  # noqa: E402
    INTENTS,
    INTENT_INDEX,
    escaped_c_string,
    load_challenge,
    load_rows,
    predict_quantized,
    quantize,
    sha256_file,
    vectorize,
    write_json,
)
from tinyai_features import (  # noqa: E402
    FEATURE_BUCKETS,
    mask_targets,
    sorted_features,
    tokenize,
)

FEATURE_GOLDEN_TEXTS = [
    "Turn on LED one",
    "switch off pin eighteen",
    "Toggle pin twenty-five",
    "configure gpio 27 as input pullup",
    "Show the status of all configured pins",
    "do not turn on the light",
    "turn off the fan, not the light",
    "what would happen if I turned the relay on",
    "list devices",
    "help",
    "Turn on GPIO23",
    "random unrelated text",
    "please enable the lamp",
    "dont switch on pin 25",
    "turn on the light and then show the status of all configured pins and tell me if the fan is off",
]


def pick_model_goldens(rows, count=24):
    """Pick deterministic, varied rows without selecting only correct ones."""
    chosen = []
    seen = set()

    def add(row):
        key = row.text.lower()
        if key not in seen:
            seen.add(key)
            chosen.append(row)

    # One from each intent first, then spread across the remaining set.
    for intent in INTENTS:
        for row in rows:
            if row.intent == intent:
                add(row)
                break
    index = 0
    while len(chosen) < count and index < len(rows):
        add(rows[index])
        index += 1
    return chosen[:count]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, default=ROOT / "model" / "intent_model.npz")
    parser.add_argument("--dataset", type=Path, default=ROOT / "data" / "dataset.csv")
    parser.add_argument("--challenge", type=Path, default=ROOT / "data" / "challenge.csv")
    parser.add_argument("--evaluation", type=Path, default=ROOT / "model" / "evaluation.json")
    parser.add_argument("--out", type=Path, default=ROOT / "components" / "model_data" / "model_weights.h")
    parser.add_argument("--manifest", type=Path, default=ROOT / "model" / "model_manifest.json")
    args = parser.parse_args()

    if not args.evaluation.exists():
        raise SystemExit("run tools/evaluate.py first; export embeds measured evaluation data")
    evaluation = json.loads(args.evaluation.read_text(encoding="utf-8"))
    bundle = np.load(args.model, allow_pickle=False)
    weights = bundle["weights"].astype(np.float64)
    biases = bundle["biases"].astype(np.float64)
    weights_q, biases_q, scale = quantize(weights, biases)
    dataset_hash_text = str(bundle["dataset_sha256"])
    dataset_hash_u32 = int(dataset_hash_text[:8], 16)
    version = f"tinyai-intent-v1-{dataset_hash_text[:8]}"

    generated_at = dt.datetime.now(dt.timezone.utc).isoformat()
    model_bytes = int(weights_q.size + biases_q.nbytes)
    class_count = len(INTENTS)
    if weights_q.shape != (class_count, FEATURE_BUCKETS):
        raise SystemExit(f"unexpected weight shape {weights_q.shape}")

    lines = [
        "/* GENERATED by tools/export_model.py. Do not edit by hand. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        '#include "tinyml.h"',
        "",
        f"#define TINYML_MODEL_VERSION {escaped_c_string(version)}",
        f"#define TINYML_MODEL_DATASET_HASH 0x{dataset_hash_u32:08x}u",
        f"#define TINYML_MODEL_BYTE_SIZE {model_bytes}u",
        "",
        f"static const int8_t TINYML_WEIGHTS[{class_count} * {FEATURE_BUCKETS}] = {{",
    ]

    flat = weights_q.reshape(-1)
    for start in range(0, flat.size, 24):
        chunk = ", ".join(str(int(v)) for v in flat[start:start + 24])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        f"static const int32_t TINYML_BIASES[{class_count}] = {{",
        "    " + ", ".join(str(int(v)) for v in biases_q),
        "};",
        "",
        f"static const char *const TINYML_LABELS[{class_count}] = {{",
    ]
    for intent in INTENTS:
        lines.append(f"    {escaped_c_string(intent)},")
    lines += [
        "};",
        "",
        "static const tinyml_model_t TINYML_MODEL = {",
        f"    .feature_buckets = {FEATURE_BUCKETS},",
        f"    .classes = {class_count},",
        "    .char_ngram_min = 3,",
        "    .char_ngram_max = 5,",
        "    .max_tokens = 24,",
        "    .max_text_bytes = 160,",
        "    .weights = TINYML_WEIGHTS,",
        "    .biases = TINYML_BIASES,",
        f"    .weight_scale = {scale:.10f}f,",
        "    .labels = TINYML_LABELS,",
        "    .version = TINYML_MODEL_VERSION,",
        "    .dataset_hash = TINYML_MODEL_DATASET_HASH,",
        f"    .confidence_threshold = {float(bundle['confidence_threshold']):.6f}f,",
        f"    .margin_threshold = {float(bundle['margin_threshold']):.6f}f,",
        "    .model_bytes = TINYML_MODEL_BYTE_SIZE,",
        "};",
        "",
        f"_Static_assert(sizeof(TINYML_LABELS) / sizeof(TINYML_LABELS[0]) == {class_count}, \"label count\");",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")

    # ------------------------------------------------------------------
    # Feature/tokenizer golden vectors. Features are shown AFTER target
    # masking, exactly as the firmware sees them.
    # ------------------------------------------------------------------
    feature_texts = list(FEATURE_GOLDEN_TEXTS)
    for row in load_rows(args.dataset):
        if len(feature_texts) >= 22:
            break
        if row.text not in feature_texts:
            feature_texts.append(row.text)
    for row in load_challenge(args.challenge):
        if len(feature_texts) >= 26:
            break
        if row.text not in feature_texts:
            feature_texts.append(row.text)

    all_rows = load_rows(args.dataset) + load_challenge(args.challenge)
    model_goldens = pick_model_goldens(all_rows, 28)
    matrix = vectorize(model_goldens)
    logits_int, probs = predict_quantized(matrix, weights_q, biases_q, scale)
    preds = probs.argmax(axis=1)
    sorted_probs = np.sort(probs, axis=1)
    confidences = sorted_probs[:, -1]
    margins = sorted_probs[:, -1] - sorted_probs[:, -2]
    confidence_threshold = float(bundle["confidence_threshold"])
    margin_threshold = float(bundle["margin_threshold"])

    golden_h = [
        "/* GENERATED by tools/export_model.py. Do not edit. */",
        "#pragma once",
        "",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        '#include "tinyml.h"',
        "",
        "#define GOLDEN_FEATURE_COUNT " + str(len(feature_texts)),
        "#define GOLDEN_MODEL_COUNT " + str(len(model_goldens)),
        "",
        "typedef struct {",
        "    const char *text;",
        "    const char *tokens[TINYML_MAX_TOKENS];",
        "    uint8_t token_count;",
        "    const uint16_t *buckets;",
        "    const uint16_t *counts;",
        "    uint16_t feature_count;",
        "} golden_feature_case_t;",
        "",
        "typedef struct {",
        "    const char *text;",
        "    int32_t logits[TINYML_INTENT_COUNT];",
        "    uint8_t predicted_intent;",
        "    float confidence;",
        "    float margin;",
        "    bool rejected;",
        "} golden_model_case_t;",
        "",
        "extern const golden_feature_case_t g_feature_golden[GOLDEN_FEATURE_COUNT];",
        "extern const golden_model_case_t g_model_golden[GOLDEN_MODEL_COUNT];",
        "",
    ]
    golden_h_path = ROOT / "tests" / "generated" / "tinyai_golden.h"
    golden_h_path.parent.mkdir(parents=True, exist_ok=True)
    golden_h_path.write_text("\n".join(golden_h), encoding="utf-8")

    golden_c = [
        "/* GENERATED by tools/export_model.py. Do not edit. */",
        '#include "tinyai_golden.h"',
        "",
    ]
    case_lines = []
    for index, text in enumerate(feature_texts):
        try:
            tokens = tokenize(text)
        except ValueError as exc:
            raise SystemExit(f"golden text invalid: {text!r}: {exc}") from exc
        features = sorted_features(mask_targets(tokens))
        bucket_values = ", ".join(str(f.bucket) for f in features)
        count_values = ", ".join(str(f.count) for f in features)
        token_values = ", ".join(escaped_c_string(tok) for tok in tokens)
        golden_c += [
            f"static const uint16_t golden_buckets_{index}[] = {{ {bucket_values} }};",
            f"static const uint16_t golden_counts_{index}[] = {{ {count_values} }};",
        ]
        case_lines += [
            "    {",
            f"        .text = {escaped_c_string(text)},",
            f"        .tokens = {{ {token_values} }},",
            f"        .token_count = {len(tokens)},",
            f"        .buckets = golden_buckets_{index},",
            f"        .counts = golden_counts_{index},",
            f"        .feature_count = {len(features)},",
            "    },",
        ]
    golden_c += [
        "",
        f"const golden_feature_case_t g_feature_golden[{len(feature_texts)}] = {{",
        *case_lines,
        "};",
        "",
    ]

    model_case_lines = []
    for index, row in enumerate(model_goldens):
        predicted = int(preds[index])
        confidence = float(confidences[index])
        margin = float(margins[index])
        rejected = (
            predicted == INTENT_INDEX["UNKNOWN"]
            or confidence < confidence_threshold
            or margin < margin_threshold
        )
        logits_values = ", ".join(str(int(v)) for v in logits_int[index])
        model_case_lines += [
            "    {",
            f"        .text = {escaped_c_string(row.text)},",
            f"        .logits = {{ {logits_values} }},",
            f"        .predicted_intent = {predicted},",
            f"        .confidence = {confidence:.9f}f,",
            f"        .margin = {margin:.9f}f,",
            f"        .rejected = {'true' if rejected else 'false'},",
            "    },",
        ]
    golden_c += [
        f"const golden_model_case_t g_model_golden[{len(model_goldens)}] = {{",
        *model_case_lines,
        "};",
        "",
    ]
    golden_c_path = ROOT / "tests" / "generated" / "tinyai_golden.c"
    golden_c_path.write_text("\n".join(golden_c), encoding="utf-8")

    manifest = {
        "generated_at_utc": generated_at,
        "generator": "tools/export_model.py",
        "version": version,
        "labels": INTENTS,
        "feature_buckets": FEATURE_BUCKETS,
        "char_ngram_range": [3, 5],
        "max_tokens": 24,
        "max_text_bytes": 160,
        "target_masking": True,
        "quantization": {
            "weights": "int8",
            "biases": "int32 (weight units)",
            "weight_scale": scale,
        },
        "sizes": {
            "weight_bytes": int(weights_q.size),
            "bias_bytes": int(biases_q.nbytes),
            "model_bytes": model_bytes,
            "header_bytes": args.out.stat().st_size,
            "golden_c_bytes": golden_c_path.stat().st_size,
        },
        "thresholds": {
            "confidence": confidence_threshold,
            "margin": margin_threshold,
        },
        "dataset_sha256": dataset_hash_text,
        "evaluation": evaluation,
        "golden": {
            "feature_cases": len(feature_texts),
            "model_cases": len(model_goldens),
        },
    }
    write_json(args.manifest, manifest)

    print(f"wrote {args.out} ({args.out.stat().st_size} bytes)")
    print(f"wrote {golden_h_path} and {golden_c_path}")
    print(f"wrote {args.manifest}")
    print(f"model: int8 weights={weights_q.size} B, biases={biases_q.nbytes} B, scale={scale:.8f}")
    print(f"quantized test accuracy from evaluation: {evaluation['test']['quantized']['accuracy']:.4f}")
    print(f"goldens: {len(feature_texts)} feature cases, {len(model_goldens)} inference cases")


if __name__ == "__main__":
    main()
